#!/usr/bin/env python3
"""Freeze the 32-row/128-output comparison viewer as placement-judge inputs."""

from __future__ import annotations

import hashlib
import json
import shutil
from datetime import UTC, datetime
from pathlib import Path
from urllib.parse import quote

from bs4 import BeautifulSoup

HERE = Path(__file__).resolve().parent
PROJECT = HERE.parents[3]
SCRATCH = Path("/mnt/localssd/hp_judge_v3_target/source")
SOURCE_HTML = SCRATCH / "viewer_v2.original.html"
SOURCE_IMAGES = SCRATCH / "img"
LOCAL_ASSETS = PROJECT / "judge/local_runs/v156_v164_v166_v166noguide_v2_20261106"
LOCAL_IMAGES = LOCAL_ASSETS / "img"
SOURCE_DIR = HERE / "source"
MANIFEST = HERE / "manifest.json"
BUCKET = "foundry-hp-enterprise-adobe-assets"
PREFIX = (
    "hp-data-artifacts/hp-3p-gpt25/"
    "hp16-v6prompt-v156-vs-v164-vs-v166-vs-v166noguide-v2-e2e32-"
    "20261106T181903Z"
)
GATEWAY = f"https://foundry-aws-corp.adobe.io/asset/{BUCKET}/{PREFIX}"
SUPPLIED_ALIAS_PREFIX = PREFIX + "-viewer"
LABEL_SLUGS = {
    "V15.6": "v15_6",
    "V16.4": "v16_4",
    "V16.6": "v16_6",
    "V16.6 no geometry": "v16_6_no_geometry",
}


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def text_sha256(value: str) -> str:
    return hashlib.sha256(value.encode("utf-8")).hexdigest()


def require(condition: bool, message: str) -> None:
    if not condition:
        raise ValueError(message)


def copy_exact(source: Path, destination: Path) -> None:
    destination.parent.mkdir(parents=True, exist_ok=True)
    if destination.exists():
        require(sha256(destination) == sha256(source), f"existing bytes differ: {destination}")
        return
    shutil.copy2(source, destination)
    require(sha256(destination) == sha256(source), f"copy verification failed: {destination}")


def main() -> int:
    require(SOURCE_HTML.is_file(), f"missing source viewer: {SOURCE_HTML}")
    require(SOURCE_IMAGES.is_dir(), f"missing source images: {SOURCE_IMAGES}")
    image_paths = sorted(SOURCE_IMAGES.glob("*.jpg"))
    require(len(image_paths) == 160, f"expected 160 source images, found {len(image_paths)}")

    SOURCE_DIR.mkdir(parents=True, exist_ok=True)
    copy_exact(SOURCE_HTML, SOURCE_DIR / "viewer.original.html")
    for image_path in image_paths:
        copy_exact(image_path, LOCAL_IMAGES / image_path.name)

    soup = BeautifulSoup(SOURCE_HTML.read_text(encoding="utf-8"), "html.parser")
    sections = soup.find_all("section")
    require(len(sections) == 32, f"expected 32 sections, found {len(sections)}")

    records: list[dict] = []
    row_inventory: list[dict] = []
    for section in sections:
        heading = section.find("h2")
        request = section.find("p", class_="req")
        meta = section.find("p", class_="meta")
        row = section.find("div", class_="row")
        require(all(value is not None for value in (heading, request, meta, row)), "section structure differs")
        row_id = heading.get_text(" ", strip=True)
        request_text = request.get_text(" ", strip=True)
        prefix = "User request:"
        require(request_text.startswith(prefix), f"{row_id}: user request prefix differs")
        scene_prompt = request_text[len(prefix) :].strip()
        product_type = meta.get_text(" ", strip=True).split(" · ", 1)[0].strip()
        require(product_type in {"laptop", "printer"}, f"{row_id}: invalid type {product_type}")

        input_details = section.find("details", class_="in")
        require(input_details is not None, f"{row_id}: missing input details")
        input_anchor = input_details.find("a", href=True)
        require(input_anchor is not None, f"{row_id}: missing twin href")
        twin_href = input_anchor["href"]
        twin_path = LOCAL_ASSETS / twin_href
        require(twin_path.is_file(), f"{row_id}: missing twin bytes {twin_path}")

        outputs = []
        figures = row.find_all("figure", recursive=False)
        require(len(figures) == 4, f"{row_id}: expected four outputs, found {len(figures)}")
        for figure in figures:
            caption = figure.find("figcaption")
            anchor = figure.find("a", href=True)
            require(caption is not None and anchor is not None, f"{row_id}: malformed output figure")
            label = caption.get_text(" ", strip=True)
            require(label in LABEL_SLUGS, f"{row_id}: unexpected variant {label}")
            href = anchor["href"]
            generated_path = LOCAL_ASSETS / href
            require(generated_path.is_file(), f"{row_id}: missing generated bytes {generated_path}")
            record_id = f"{row_id}__{LABEL_SLUGS[label]}"
            output = {
                "label": label,
                "record_id": record_id,
                "href": href,
                "sha256": sha256(generated_path),
            }
            outputs.append(output)
            records.append(
                {
                    "id": record_id,
                    "dataset_role": "requested_e2e_comparison_diagnostic",
                    "source_row_id": row_id,
                    "variant": label,
                    "product_type": product_type,
                    "device_type": product_type,
                    "scene_prompt": scene_prompt,
                    "scene_prompt_sha256": text_sha256(scene_prompt),
                    "scene_prompt_source": {
                        "kind": "user_request_from_source_viewer",
                        "source_row_id": row_id,
                        "source_viewer_sha256": sha256(SOURCE_HTML),
                        "rewritten_prompt_included": False,
                    },
                    # V3's frozen validator accepts this one literal. The true source-stage
                    # statement is retained separately and shown in the report.
                    "image_stage": "scene_generation",
                    "source_image_stage": "e2e_comparison_output",
                    "stage_compatibility_adapter": {
                        "applied": True,
                        "reason": "User requested the calibrated V3 placement judge on an E2E comparison report.",
                        "judge_claim_boundary": "Out-of-domain diagnostic; V3 was calibrated on scene-generation images.",
                    },
                    "generated_image": {
                        "local_path": str(generated_path.resolve()),
                        "sha256": sha256(generated_path),
                        "bytes": generated_path.stat().st_size,
                        "s3_uri": f"s3://{BUCKET}/{PREFIX}/{href}",
                        "public_url": f"{GATEWAY}/{quote(href)}",
                    },
                    "twin_image": {
                        "local_path": str(twin_path.resolve()),
                        "sha256": sha256(twin_path),
                        "bytes": twin_path.stat().st_size,
                        "s3_uri": f"s3://{BUCKET}/{PREFIX}/{twin_href}",
                        "public_url": f"{GATEWAY}/{quote(twin_href)}",
                    },
                    "hashes": {
                        "generated_image_sha256": sha256(generated_path),
                        "twin_image_sha256": sha256(twin_path),
                        "scene_prompt_sha256": text_sha256(scene_prompt),
                    },
                }
            )
        require(len({item["record_id"] for item in outputs}) == 4, f"{row_id}: duplicate variants")
        row_inventory.append(
            {
                "row_id": row_id,
                "product_type": product_type,
                "scene_prompt": scene_prompt,
                "twin_href": twin_href,
                "twin_sha256": sha256(twin_path),
                "outputs": outputs,
            }
        )

    require(len(records) == 128, f"expected 128 records, found {len(records)}")
    ids = [record["id"] for record in records]
    require(len(ids) == len(set(ids)), "duplicate record IDs")
    manifest = {
        "schema_version": "placement-v3-e2e-comparison-adapter-v1",
        "generated_at_utc": datetime.now(UTC).isoformat(),
        "expected_count": 128,
        "dataset_role": "requested_e2e_comparison_diagnostic",
        "source": {
            "title": "HP16 V6 · V15.6 vs V16.4 vs V16.6 vs V16.6 no geometry",
            "actual_viewer_url": f"{GATEWAY}/viewer.html",
            "user_supplied_alias_url": (
                f"https://foundry-aws-corp.adobe.io/asset/{BUCKET}/"
                f"{SUPPLIED_ALIAS_PREFIX}/viewer.html"
            ),
            "s3_prefix": f"s3://{BUCKET}/{PREFIX}/",
            "viewer_sha256": sha256(SOURCE_HTML),
            "viewer_bytes": SOURCE_HTML.stat().st_size,
            "rows": 32,
            "generated_outputs": 128,
            "input_twins": 32,
        },
        "judge_application": {
            "selected_protocol": "natural-placement V3 consensus-v2",
            "claim_boundary": "Research candidate for human review; not an automatic acceptance gate.",
            "source_stage": "e2e_comparison_output",
            "calibrated_stage": "scene_generation",
            "out_of_domain_diagnostic": True,
        },
        "row_inventory": row_inventory,
        "records": records,
    }
    MANIFEST.write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(
        json.dumps(
            {
                "manifest": str(MANIFEST),
                "records": len(records),
                "rows": len(row_inventory),
                "manifest_sha256": sha256(MANIFEST),
                "assets": str(LOCAL_ASSETS),
            },
            indent=2,
        )
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
